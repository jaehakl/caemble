const nativeConstants: Readonly<Record<string, unknown>> = Object.freeze({
  e: Math.E,
  pi: Math.PI,
  tau: 2 * Math.PI,
})

export const CALCULATION_MATHJS_RUNTIME: Readonly<Record<CalculationMathJsName, unknown>> = Object.freeze(
  Object.fromEntries(
    CALCULATION_MATHJS_NAMES.map((name) => {
      const value = name in nativeConstants ? nativeConstants[name] : customMath[name]
      if (value === undefined) throw new Error(`Calculation Math.js custom bundle is missing ${name}.`)
      if (typeof value !== 'function') return [name, value]
      const implementation = value as (...arguments_: unknown[]) => unknown
      return [name, Object.freeze((...arguments_: unknown[]) => implementation(...arguments_))]
    }),
  ) as Record<CalculationMathJsName, unknown>,
)
